// Constantes de la curva (valores EXACTOS del HTML, sin redondear).
export const MI_ZONA_GAMMA = 1.0874372386932374
export const MI_ZONA_RATIO_MIN = 0.25113318691468045
export const MI_ZONA_MAX_PCT = 9.0
export const MI_ZONA_MIN_PCT = 0.0
export const MI_ZONA_MIN_POLYGONS = 2

// gmvInsideRatio — RÉPLICA EXACTA de getCommissionForSelection() del HTML.
// Devuelve la fracción [0,1] del GMV que, saliendo de las zonas seleccionadas,
// se queda dentro de ellas. null si el set no genera GMV. Ver cabecera.
export function gmvInsideRatio(selectedIds) {
  const selectedSet = new Set(selectedIds)
  let gmvM1 = 0
  let gmvM2 = 0
  for (const origin of selectedIds) {
    const row = LIMA_GMV_MATRIX[origin]
    if (!row) continue
    for (const dest in row) {
      const value = row[dest]
      gmvM2 += value
      if (selectedSet.has(dest)) gmvM1 += value
    }
  }
  return gmvM2 > 0 ? gmvM1 / gmvM2 : null
}

// commissionForRatio — RÉPLICA EXACTA de commissionForRatio() del HTML.
// ratio≤min → 9%; ratio≥1 → 0%; intermedio = 9·(1 − t^gamma) con
// t=(ratio−min)/(1−min). null si ratio es null/undefined.
export function commissionForRatio(ratio) {
  if (ratio === null || ratio === undefined) return null
  if (ratio <= MI_ZONA_RATIO_MIN) return MI_ZONA_MAX_PCT
  if (ratio >= 1.0) return MI_ZONA_MIN_PCT
  const t = (ratio - MI_ZONA_RATIO_MIN) / (1.0 - MI_ZONA_RATIO_MIN)
  return MI_ZONA_MAX_PCT - (MI_ZONA_MAX_PCT - MI_ZONA_MIN_PCT) * Math.pow(t, MI_ZONA_GAMMA)
}

// Atajo: comisión Mi Zona (en pp) para un set de zonas seleccionadas.
export function miZonaCommissionForSelection(selectedIds) {
  if (selectedIds.length < MI_ZONA_MIN_POLYGONS) return null
  return commissionForRatio(gmvInsideRatio(selectedIds))
}
